import re


def L(title, level, desc, usage, examples, mistakes, formula=None, signals=None):
    return {
        "title": title, "slug": re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-"),
        "level": level, "description": desc, "formula": formula or {}, "usage": usage,
        "signals": signals or [], "examples": [{"en": e, "vi": v} for e, v in examples],
        "common_mistakes": [{"wrong": w, "right": r} for w, r in mistakes], "exercises": [],
    }


def F(a, n="", q=""):
    return {k: v for k, v in (("affirmative", a), ("negative", n), ("question", q)) if v}


